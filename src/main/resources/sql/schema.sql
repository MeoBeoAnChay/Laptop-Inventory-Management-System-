);
GO

-- 11. IMPORT_REQUEST_DETAILS
CREATE TABLE IMPORT_REQUEST_DETAILS (
    ImportRequestDetailID INT IDENTITY(1,1) PRIMARY KEY,
    ImportRequestID INT NOT NULL,
    ProductID INT NOT NULL,
    Quantity INT NOT NULL CHECK (Quantity > 0),
    UnitPrice DECIMAL(18, 2) NOT NULL DEFAULT 0.00,
    CONSTRAINT FK_IRD_ImportRequests FOREIGN KEY (ImportRequestID) REFERENCES IMPORT_REQUESTS(ImportRequestID) ON DELETE CASCADE,
