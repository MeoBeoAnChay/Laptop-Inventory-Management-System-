    CONSTRAINT FK_ImportRequests_Suppliers FOREIGN KEY (SupplierID) REFERENCES SUPPLIERS(SupplierID),
    CONSTRAINT FK_ImportRequests_CreatedBy FOREIGN KEY (CreatedBy) REFERENCES USERS(UserID),
