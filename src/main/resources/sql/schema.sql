-- 7. PRODUCTS
CREATE TABLE PRODUCTS (
    ProductID INT IDENTITY(1,1) PRIMARY KEY,
    ProductCode NVARCHAR(50) NOT NULL UNIQUE,
    ProductName NVARCHAR(150) NOT NULL,
    ProductLineID INT NOT NULL,
    CPU NVARCHAR(100) NOT NULL,
    RAM NVARCHAR(50) NOT NULL,
    Storage NVARCHAR(100) NOT NULL,
    GPU NVARCHAR(100) NULL,
    Screen NVARCHAR(50) NULL,
    UnitPrice DECIMAL(18, 2) NOT NULL DEFAULT 0.00,
    Status NVARCHAR(20) NOT NULL DEFAULT 'ACTIVE', -- ACTIVE, INACTIVE, DISCONTINUED
    CONSTRAINT FK_Products_ProductLines FOREIGN KEY (ProductLineID) REFERENCES PRODUCT_LINES(ProductLineID)
);
GO

